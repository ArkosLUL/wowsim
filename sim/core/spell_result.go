package core

import (
	"fmt"
	"math"

	"github.com/wowsims/wotlk/sim/core/stats"
)

type SpellResult struct {
	// Target of the spell.
	Target *Unit

	// Results
	Outcome HitOutcome
	Damage  float64 // Damage done by this cast.
	Threat  float64 // The amount of threat generated by this cast.

	ResistanceMultiplier float64 // Partial Resists / Armor multiplier
	PreOutcomeDamage     float64 // Damage done by this cast before Outcome is applied
	ArmorReduced         float64 // what armor took off the base damage (the server's cleanDamage)

	castWasInstant bool

	inUse bool
	owner *Spell // the spell whose spares this is, nil for its resultCache
}

// NewResult hands out the spell's cached result, or a spare while that one's in use, e.g. by a missile
// in flight. A disposed one (CalcAndDealDamage returns those) is only safe to read until the next NewResult.
func (spell *Spell) NewResult(target *Unit) *SpellResult {
	result := &spell.resultCache
	if result.inUse {
		result = spell.spareResult()
	}

	result.Target = target
	result.Damage = 0
	result.Threat = 0
	result.ArmorReduced = 0
	result.Outcome = OutcomeEmpty // for blocks
	result.castWasInstant = spell.CurCast.CastTime == 0
	result.inUse = true

	return result
}

// spareResult comes back zeroed, the same as a new one.
func (spell *Spell) spareResult() *SpellResult {
	n := len(spell.freeResults)
	if n == 0 {
		result := &SpellResult{owner: spell}
		spell.spareResults = append(spell.spareResults, result)
		return result
	}
	result := spell.freeResults[n-1]
	spell.freeResults = spell.freeResults[:n-1]
	*result = SpellResult{owner: spell}
	return result
}

func (spell *Spell) DisposeResult(result *SpellResult) {
	// only an in-use spare goes back, so none is ever free twice
	if result.inUse && result.owner != nil {
		result.owner.freeResults = append(result.owner.freeResults, result)
	}
	result.inUse = false
}

// Every result is free again when an iteration starts: whatever held one last iteration is gone.
func (spell *Spell) resetResults() {
	spell.resultCache.inUse = false
	for _, result := range spell.spareResults {
		result.inUse = false
	}
	spell.freeResults = append(spell.freeResults[:0], spell.spareResults...)
}

func (result *SpellResult) Landed() bool {
	return result.Outcome.Matches(OutcomeLanded)
}

func (result *SpellResult) DidCrit() bool {
	return result.Outcome.Matches(OutcomeCrit)
}

// FromInstantCast is whether the cast behind this result had no cast time, which decides how long a
// proc it feeds waits (DelayedPeriodicApplier.DelayFromInstantCast). Read at the cast, not at the
// hit: a missile outlives CurCast, which the next cast of the same spell overwrites mid-flight.
func (result *SpellResult) FromInstantCast() bool {
	return result.castWasInstant
}

func (result *SpellResult) DamageString() string {
	outcomeStr := result.Outcome.String()
	if !result.Landed() {
		return outcomeStr
	}
	return fmt.Sprintf("%s for %0.3f damage", outcomeStr, result.Damage)
}
func (result *SpellResult) HealingString() string {
	return fmt.Sprintf("%s for %0.3f healing", result.Outcome.String(), result.Damage)
}

// MeleeAttackPower leaves out the creature-type attack power: a weapon hit gets it after its weapon
// percent (weaponAttackPowerBonus), a spell's attack power coefficient never.
func (spell *Spell) MeleeAttackPower() float64 {
	return spell.Unit.stats[stats.AttackPower]
}

func (spell *Spell) RangedAttackPower(target *Unit) float64 {
	return spell.Unit.stats[stats.RangedAttackPower] + target.PseudoStats.BonusRangedAttackPowerTaken
}

// RangedAttackPowerSpellBonus is a spell_bonus_data row's own ap_bonus/ap_dot_bonus source
// (Unit::GetTotalAttackPowerValue), Hunter's Mark included. A weapon hit's weapon part reads the bare ranged
// attack power and gets the mark after the weapon percent instead (weaponAttackPowerBonus).
func (spell *Spell) RangedAttackPowerSpellBonus(target *Unit) float64 {
	return spell.RangedAttackPower(target)
}

// weaponAttackPowerBonus is Unit::MeleeDamageBonusDone's flat bonus on a weapon hit: the target's Hunter's
// Mark on a ranged one plus the creature-type attack power (SPELL_AURA_MOD_*_ATTACK_POWER_VERSUS), summed
// first, then int32(sum / 14 × the weapon's speed, normalized or not), added after the weapon percent.
func (spell *Spell) weaponAttackPowerBonus(target *Unit) float64 {
	if spell.Flags.Matches(SpellFlagIgnoreAttackerModifiers) {
		return 0
	}
	ap := spell.Unit.PseudoStats.MobTypeAttackPower
	ranged := spell.ProcMask.Matches(ProcMaskRanged)
	if ranged {
		ap += target.PseudoStats.BonusRangedAttackPowerTaken
	}
	if ap == 0 {
		return 0
	}
	weaponHit, normalized := spell.dealsWeaponDamage()
	if !weaponHit {
		return 0
	}
	weapon := spell.Unit.AutoAttacks.MH()
	switch {
	case spell.ProcMask.Matches(ProcMaskMeleeOH):
		weapon = spell.Unit.AutoAttacks.OH()
	case ranged:
		weapon = spell.Unit.AutoAttacks.Ranged()
	}
	speed := weapon.SwingSpeed
	if normalized {
		speed = weapon.NormalizedSwingSpeed
	}
	return math.Trunc(ap / DefaultAttackPowerPerDPS * speed)
}

// weaponBonusMultiplier is the share of the attacker multiplier weaponAttackPowerBonus takes. A physical hit's
// weapon damage already carries its hand's TOTAL_PCT, the aura 79 percents (DamageDealtMultiplier, the
// physical school's, TotalPctMultiplier), and Unit::MeleeDamageBonusDone skips aura 79 for physical damage.
func (spell *Spell) weaponBonusMultiplier(attackerMultiplier float64) float64 {
	if !spell.SpellSchool.Matches(SpellSchoolPhysical) {
		return attackerMultiplier
	}
	totalPct := spell.Unit.PseudoStats.DamageDealtMultiplier *
		spell.Unit.PseudoStats.SchoolDamageDealtMultiplier[stats.SchoolIndexPhysical] *
		spell.TotalPctMultiplier
	if totalPct == 0 {
		return 0
	}
	return attackerMultiplier / totalPct
}

// WeaponBonusForDonePct is what a done percent that class code multiplies into a weapon hit's base damage
// adds to the hit's flat attack power bonus: Unit::MeleeDamageBonusDone's DoneTotalMod scales both. It's in
// base damage, so add it after the percent.
func (spell *Spell) WeaponBonusForDonePct(target *Unit, donePct float64) float64 {
	bonus := spell.weaponAttackPowerBonus(target)
	if bonus == 0 {
		return 0
	}
	if spell.wholeStrike && spell.SpellSchool.Matches(SpellSchoolPhysical) {
		// doneDamage adds the bonus to a whole strike before any percent
		return bonus * (donePct - 1)
	}
	return bonus * spell.weaponBonusMultiplier(1) * (donePct - 1)
}

// doneDamage is SpellDamageBonusDone's or MeleeDamageBonusDone's result, a whole number: the server
// truncates it, a dot's amount at application, and keeps every later step whole too.
func (spell *Spell) doneDamage(target *Unit, baseDamage float64, attackerMultiplier float64, isPeriodic bool) float64 {
	if spell.wholeStrike && !isPeriodic && spell.SpellSchool.Matches(SpellSchoolPhysical) {
		// float(int32(pdamage) + DoneFlatBenefit) * DoneTotalMod, the hand's percent already in pdamage
		if baseDamage > 0 {
			baseDamage += spell.weaponAttackPowerBonus(target)
		}
		return math.Trunc(baseDamage * spell.strikeDoneMultiplier(target))
	}
	damage := baseDamage * attackerMultiplier
	if !isPeriodic && baseDamage > 0 {
		if bonus := spell.weaponAttackPowerBonus(target); bonus != 0 {
			damage += bonus * spell.weaponBonusMultiplier(attackerMultiplier)
		}
	}
	return math.Trunc(damage)
}

func (spell *Spell) BonusWeaponDamage() float64 {
	return spell.Unit.PseudoStats.BonusDamage
}

// ExpertisePercentage is continuous: only the character sheet's copy is rounded
// to whole points on the server. The attack table truncates it to basis points.
func (spell *Spell) ExpertisePercentage() float64 {
	expertiseRating := spell.Unit.stats[stats.Expertise] + spell.BonusExpertiseRating
	return expertiseRating / ExpertisePerQuarterPercentReduction / 400
}

func (spell *Spell) PhysicalHitChance(attackTable *AttackTable) float64 {
	hitRating := spell.Unit.stats[stats.MeleeHit] +
		spell.BonusHitRating +
		attackTable.Defender.PseudoStats.BonusMeleeHitRatingTaken
	return hitRating / (MeleeHitRatingPerHitChance * 100)
}

func (spell *Spell) PhysicalCritChance(attackTable *AttackTable) float64 {
	if spell.Unit.Type == EnemyUnit {
		return spell.enemyCritChance(attackTable)
	}
	critRating := spell.Unit.stats[stats.MeleeCrit] +
		spell.BonusCritRating +
		attackTable.Defender.PseudoStats.BonusCritRatingTaken
	return critRating/(CritRatingPerCritChance*100) - attackTable.MeleeCritSuppression
}
func (spell *Spell) PhysicalCritCheck(sim *Simulation, attackTable *AttackTable) bool {
	return sim.UnitRandomFloat(spell.Unit, "Physical Crit Roll") < spell.PhysicalCritChance(attackTable)
}

// SpellPower is whole, like the server's int32 (Unit::SpellBaseDamageBonusDone).
func (spell *Spell) SpellPower() float64 {
	return math.Trunc(spell.Unit.GetStat(stats.SpellPower) +
		spell.BonusSpellPower +
		spell.Unit.PseudoStats.MobTypeSpellPower)
}

// PowerBonus is one spell power or attack power bonus the way SpellDamageBonusDone and SpellHealingBonusDone
// add it: its own int32, off the product of two float32s. 0.13 × 1700 is 220 there, 221 in float64.
func PowerBonus(coefficient float64, power float64) float64 {
	return float64(int32(float32(coefficient) * float32(power)))
}

func (spell *Spell) SpellHitChance(target *Unit) float64 {
	hitRating := spell.Unit.stats[stats.SpellHit] +
		spell.BonusHitRating +
		target.PseudoStats.BonusSpellHitRatingTaken

	return hitRating / (SpellHitRatingPerHitChance * 100)
}

// spellMissThresholdBP is what MagicSpellHitResult compares its roll against. A
// binary spell folds its whole resist chance in here instead of resisting part of
// the damage later.
func (spell *Spell) spellMissThresholdBP(attackTable *AttackTable) int32 {
	threshold := SpellMissBP(
		attackTable.DefenderLevel-attackTable.AttackerLevel,
		float32(spell.SpellHitChance(attackTable.Defender)*100),
		attackTable.Defender.Type == PlayerUnit)

	if spell.Flags.Matches(SpellFlagBinary) && !spell.SpellSchool.Matches(SpellSchoolPhysical|SpellSchoolHoly) {
		binaryResist := EffectiveResistChance(
			attackTable.Defender.schoolResistance(spell.SpellSchool),
			attackTable.Attacker.stats[stats.SpellPenetration],
			attackTable.Attacker.Level,
			attackTable.Defender.Level,
			true)
		threshold += int32(binaryResist * MaxRollBP)
	}

	return threshold
}

// SpellChanceToMiss is the share of casts that neither hit nor resist. The roll is
// irand(1, 10000), so the true rate sits a hundredth of a point under the
// threshold: 16.99% against a boss, not 17%.
func (spell *Spell) SpellChanceToMiss(attackTable *AttackTable) float64 {
	return math.Max(0, float64(spell.spellMissThresholdBP(attackTable)-1)/MaxRollBP)
}

func (spell *Spell) MagicHitCheck(sim *Simulation, attackTable *AttackTable) bool {
	roll := int32(sim.UnitRandomFloat(spell.Unit, "Magical Hit Roll")*MaxRollBP) + 1
	return roll >= spell.spellMissThresholdBP(attackTable)
}

func (spell *Spell) spellCritRating(target *Unit) float64 {
	return spell.Unit.stats[stats.SpellCrit] +
		spell.BonusCritRating +
		target.PseudoStats.BonusCritRatingTaken +
		target.PseudoStats.BonusSpellCritRatingTaken
}

// SpellCritChance has no level-based suppression: SpellDoneCritChance only
// applies the skill term to melee and ranged damage class spells, which go
// through PhysicalCritChance instead.
func (spell *Spell) SpellCritChance(target *Unit) float64 {
	return spell.spellCritRating(target) / (CritRatingPerCritChance * 100)
}
func (spell *Spell) MagicCritCheck(sim *Simulation, target *Unit) bool {
	critChance := spell.SpellCritChance(target)
	return sim.UnitRandomFloat(spell.Unit, "Magical Crit Roll") < critChance
}

func (spell *Spell) HealingPower(target *Unit) float64 {
	return spell.SpellPower() + target.PseudoStats.BonusHealingTaken
}
func (spell *Spell) healingCritRating() float64 {
	return spell.Unit.GetStat(stats.SpellCrit) + spell.BonusCritRating
}
func (spell *Spell) HealingCritChance() float64 {
	return spell.healingCritRating() / (CritRatingPerCritChance * 100)
}

func (spell *Spell) HealingCritCheck(sim *Simulation) bool {
	critChance := spell.HealingCritChance()
	return sim.UnitRandomFloat(spell.Unit, "Healing Crit Roll") < critChance
}

// ApplyPostOutcomeDamageModifiers leaves the damage whole, as the server's crit, glancing and absorb math does.
func (spell *Spell) ApplyPostOutcomeDamageModifiers(sim *Simulation, result *SpellResult) {
	for i := range result.Target.DynamicDamageTakenModifiers {
		result.Target.DynamicDamageTakenModifiers[i](sim, spell, result)
	}
	result.Damage = max(0, math.Trunc(result.Damage))
}

// For spells that do no damage but still have a hit/miss check.
func (spell *Spell) CalcOutcome(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	attackTable := spell.Unit.AttackTables[target.UnitIndex]
	result := spell.NewResult(target)

	outcomeApplier(sim, result, attackTable)
	result.Threat = spell.ThreatFromDamage(result.Outcome, result.Damage) + spell.threatBonus(result)
	return result
}

// calcDamageInternal takes the hit from doneDamage's result on. baseDamage is only logged.
func (spell *Spell) calcDamageInternal(sim *Simulation, target *Unit, baseDamage float64, doneDamage float64, isPeriodic bool, outcomeApplier OutcomeApplier) *SpellResult {
	attackTable := spell.Unit.AttackTables[target.UnitIndex]

	result := spell.NewResult(target)
	result.Damage = doneDamage

	if sim.Log == nil {
		result.applyTargetModifiers(spell, attackTable, isPeriodic)
		result.applyResistances(sim, spell, isPeriodic, attackTable)
		outcomeApplier(sim, result, attackTable)
		result.applyPartialResist(spell)
		spell.ApplyPostOutcomeDamageModifiers(sim, result)
	} else {
		afterAttackMods := result.Damage
		result.applyTargetModifiers(spell, attackTable, isPeriodic)
		afterTargetMods := result.Damage
		result.applyResistances(sim, spell, isPeriodic, attackTable)
		afterResistances := result.Damage
		outcomeApplier(sim, result, attackTable)
		result.applyPartialResist(spell)
		afterOutcome := result.Damage
		spell.ApplyPostOutcomeDamageModifiers(sim, result)
		afterPostOutcome := result.Damage

		spell.Unit.Log(
			sim,
			"%s %s [DEBUG] MAP: %0.01f, RAP: %0.01f, SP: %0.01f, BaseDamage:%0.01f, AfterAttackerMods:%0.01f, AfterTargetMods:%0.01f, AfterResistances:%0.01f, AfterOutcome:%0.01f, AfterPostOutcome:%0.01f",
			target.LogLabel(), spell.ActionID, spell.Unit.GetStat(stats.AttackPower), spell.Unit.GetStat(stats.RangedAttackPower), spell.Unit.GetStat(stats.SpellPower), baseDamage, afterAttackMods, afterTargetMods, afterResistances, afterOutcome, afterPostOutcome)
	}

	result.Threat = spell.ThreatFromDamage(result.Outcome, result.Damage)
	if !isPeriodic {
		result.Threat += spell.threatBonus(result)
	}

	return result
}
func (spell *Spell) CalcDamage(sim *Simulation, target *Unit, baseDamage float64, outcomeApplier OutcomeApplier) *SpellResult {
	attackerMultiplier := spell.AttackerDamageMultiplier(spell.Unit.AttackTables[target.UnitIndex])
	return spell.calcDamageInternal(sim, target, baseDamage, spell.doneDamage(target, baseDamage, attackerMultiplier, false), false, outcomeApplier)
}

// CalcDamageDone is CalcDamage for a hit whose done amount a script worked out itself, whole.
func (spell *Spell) CalcDamageDone(sim *Simulation, target *Unit, doneDamage float64, outcomeApplier OutcomeApplier) *SpellResult {
	return spell.calcDamageInternal(sim, target, doneDamage, doneDamage, false, outcomeApplier)
}
func (spell *Spell) CalcPeriodicDamage(sim *Simulation, target *Unit, baseDamage float64, outcomeApplier OutcomeApplier) *SpellResult {
	attackerMultiplier := spell.AttackerDamageMultiplier(spell.Unit.AttackTables[target.UnitIndex])
	return spell.calcDamageInternal(sim, target, baseDamage, spell.doneDamage(target, baseDamage, attackerMultiplier, true), true, outcomeApplier)
}
func (dot *Dot) CalcSnapshotDamage(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	done := dot.Spell.doneDamage(target, dot.SnapshotBaseDamage, dot.SnapshotAttackerMultiplier, true)
	if dot.SnapshotStacks > 1 {
		done *= float64(dot.SnapshotStacks)
	}
	return dot.Spell.calcDamageInternal(sim, target, dot.SnapshotBaseDamage, done, true, outcomeApplier)
}

func (spell *Spell) DealOutcome(sim *Simulation, result *SpellResult) {
	spell.DealDamage(sim, result)
}
func (spell *Spell) CalcAndDealOutcome(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	result := spell.CalcOutcome(sim, target, outcomeApplier)
	spell.DealDamage(sim, result)
	return result
}

// Applies the fully computed spell result to the sim.
func (spell *Spell) dealDamageInternal(sim *Simulation, isPeriodic bool, result *SpellResult) {
	if sim.CurrentTime >= 0 {
		spell.SpellMetrics[result.Target.UnitIndex].TotalDamage += result.Damage
		spell.SpellMetrics[result.Target.UnitIndex].TotalThreat += result.Threat
	}

	// Mark total damage done in raid so far for health based fights.
	// Don't include damage done by EnemyUnits to Players
	if result.Target.Type == EnemyUnit {
		sim.Encounter.DamageTaken += result.Damage
	}

	if sim.Log != nil {
		if isPeriodic {
			spell.Unit.Log(sim, "%s %s tick %s. (Threat: %0.3f)", result.Target.LogLabel(), spell.ActionID, result.DamageString(), result.Threat)
		} else {
			spell.Unit.Log(sim, "%s %s %s. (Threat: %0.3f)", result.Target.LogLabel(), spell.ActionID, result.DamageString(), result.Threat)
		}
	}

	if !spell.Flags.Matches(SpellFlagNoOnDamageDealt) {
		if isPeriodic {
			spell.Unit.OnPeriodicDamageDealt(sim, spell, result)
			result.Target.OnPeriodicDamageTaken(sim, spell, result)
		} else {
			spell.Unit.OnSpellHitDealt(sim, spell, result)
			result.Target.OnSpellHitTaken(sim, spell, result)
		}
	}

	spell.DisposeResult(result)
}
func (spell *Spell) DealDamage(sim *Simulation, result *SpellResult) {
	spell.dealDamageInternal(sim, false, result)
}
func (spell *Spell) DealPeriodicDamage(sim *Simulation, result *SpellResult) {
	spell.dealDamageInternal(sim, true, result)
}

func (spell *Spell) CalcAndDealDamage(sim *Simulation, target *Unit, baseDamage float64, outcomeApplier OutcomeApplier) *SpellResult {
	result := spell.CalcDamage(sim, target, baseDamage, outcomeApplier)
	spell.DealDamage(sim, result)
	return result
}
func (spell *Spell) CalcAndDealPeriodicDamage(sim *Simulation, target *Unit, baseDamage float64, outcomeApplier OutcomeApplier) *SpellResult {
	result := spell.CalcPeriodicDamage(sim, target, baseDamage, outcomeApplier)
	spell.DealPeriodicDamage(sim, result)
	return result
}
func (dot *Dot) CalcAndDealPeriodicSnapshotDamage(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	result := dot.CalcSnapshotDamage(sim, target, outcomeApplier)
	dot.Spell.DealPeriodicDamage(sim, result)
	return result
}

func (spell *Spell) calcHealingInternal(sim *Simulation, target *Unit, baseHealing float64, casterMultiplier float64, outcomeApplier OutcomeApplier) *SpellResult {
	attackTable := spell.Unit.AttackTables[target.UnitIndex]

	result := spell.NewResult(target)

	// SpellHealingBonusDone, SpellHealingBonusTaken and SpellCriticalHealingBonus each return a whole number
	if sim.Log == nil {
		result.Damage = wholeHeal(baseHealing * casterMultiplier)
		result.Damage = wholeHeal(spell.applyTargetHealingModifiers(result.Damage, attackTable))
		outcomeApplier(sim, result, attackTable)
		result.Damage = wholeHeal(result.Damage)
	} else {
		result.Damage = wholeHeal(baseHealing * casterMultiplier)
		afterCasterMods := result.Damage
		result.Damage = wholeHeal(spell.applyTargetHealingModifiers(result.Damage, attackTable))
		afterTargetMods := result.Damage
		outcomeApplier(sim, result, attackTable)
		result.Damage = wholeHeal(result.Damage)
		afterOutcome := result.Damage

		spell.Unit.Log(
			sim,
			"%s %s [DEBUG] HealingPower: %0.01f, BaseHealing:%0.01f, AfterCasterMods:%0.01f, AfterTargetMods:%0.01f, AfterOutcome:%0.01f",
			target.LogLabel(), spell.ActionID, spell.HealingPower(target), baseHealing, afterCasterMods, afterTargetMods, afterOutcome)
	}

	return result
}

// wholeHeal is the server's uint32(max(heal, 0)).
func wholeHeal(heal float64) float64 {
	return max(0, math.Trunc(heal))
}

func (spell *Spell) CalcHealing(sim *Simulation, target *Unit, baseHealing float64, outcomeApplier OutcomeApplier) *SpellResult {
	return spell.calcHealingInternal(sim, target, baseHealing, spell.CasterHealingMultiplier(), outcomeApplier)
}
func (dot *Dot) CalcSnapshotHealing(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	return dot.Spell.calcHealingInternal(sim, target, dot.SnapshotBaseDamage, dot.SnapshotAttackerMultiplier, outcomeApplier)
}

// Applies the fully computed spell result to the sim.
func (spell *Spell) dealHealingInternal(sim *Simulation, isPeriodic bool, result *SpellResult) {
	spell.SpellMetrics[result.Target.UnitIndex].TotalHealing += result.Damage
	// the threat is the health gained, so none from overhealing
	gain := result.Damage
	if result.Target.HasHealthBar() {
		before := result.Target.CurrentHealth()
		result.Target.GainHealth(sim, result.Damage, spell.HealthMetrics(result.Target))
		gain = result.Target.CurrentHealth() - before
	}
	result.Threat = spell.healThreat(sim, gain)

	if sim.Log != nil {
		if isPeriodic {
			spell.Unit.Log(sim, "%s %s tick %s. (Threat: %0.3f)", result.Target.LogLabel(), spell.ActionID, result.HealingString(), result.Threat)
		} else {
			spell.Unit.Log(sim, "%s %s %s. (Threat: %0.3f)", result.Target.LogLabel(), spell.ActionID, result.HealingString(), result.Threat)
		}
	}

	if isPeriodic {
		spell.Unit.OnPeriodicHealDealt(sim, spell, result)
		result.Target.OnPeriodicHealTaken(sim, spell, result)
	} else {
		spell.Unit.OnHealDealt(sim, spell, result)
		result.Target.OnHealTaken(sim, spell, result)
	}

	spell.DisposeResult(result)
}
func (spell *Spell) DealHealing(sim *Simulation, result *SpellResult) {
	spell.dealHealingInternal(sim, false, result)
}
func (spell *Spell) DealPeriodicHealing(sim *Simulation, result *SpellResult) {
	spell.dealHealingInternal(sim, true, result)
}

func (spell *Spell) CalcAndDealHealing(sim *Simulation, target *Unit, baseHealing float64, outcomeApplier OutcomeApplier) *SpellResult {
	result := spell.CalcHealing(sim, target, baseHealing, outcomeApplier)
	spell.DealHealing(sim, result)
	return result
}
func (spell *Spell) CalcAndDealPeriodicHealing(sim *Simulation, target *Unit, baseHealing float64, outcomeApplier OutcomeApplier) *SpellResult {
	// This is currently identical to CalcAndDealHealing, but keeping it separate in case they become different in the future.
	return spell.CalcAndDealHealing(sim, target, baseHealing, outcomeApplier)
}
func (dot *Dot) CalcAndDealPeriodicSnapshotHealing(sim *Simulation, target *Unit, outcomeApplier OutcomeApplier) *SpellResult {
	result := dot.CalcSnapshotHealing(sim, target, outcomeApplier)
	dot.Spell.DealPeriodicHealing(sim, result)
	return result
}

func (spell *Spell) WaitTravelTime(sim *Simulation, callback func(*Simulation)) {
	if callback == nil {
		panic("WaitTravelTime: callback must not be nil")
	}
	sim.startLanding(sim.CurrentTime+spell.TravelTime(), spell.Unit, callback, nil, nil)
}

// DealDamageAfterTravel is WaitTravelTime with a landing that only deals result, minus the closure's
// allocation.
func (spell *Spell) DealDamageAfterTravel(sim *Simulation, result *SpellResult) {
	sim.startLanding(sim.CurrentTime+spell.TravelTime(), spell.Unit, nil, spell, result)
}

// Returns the combined attacker modifiers.
func (spell *Spell) AttackerDamageMultiplier(attackTable *AttackTable) float64 {
	return spell.attackerDamageMultiplierInternal(attackTable) *
		spell.DamageMultiplier *
		spell.DamageMultiplierAdditive
}
func (spell *Spell) attackerDamageMultiplierInternal(attackTable *AttackTable) float64 {
	if spell.Flags.Matches(SpellFlagIgnoreAttackerModifiers) {
		return 1
	}

	return spell.Unit.PseudoStats.DamageDealtMultiplier *
		spell.Unit.PseudoStats.SchoolDamageDealtMultiplier[spell.SchoolIndex] *
		attackTable.DamageDealtMultiplier
}

func (result *SpellResult) applyTargetModifiers(spell *Spell, attackTable *AttackTable, isPeriodic bool) {
	if spell.Flags.Matches(SpellFlagIgnoreTargetModifiers) {
		return
	}

	if spell.SpellSchool.Matches(SpellSchoolPhysical) && spell.Flags.Matches(SpellFlagIncludeTargetBonusDamage) {
		result.Damage += attackTable.Defender.PseudoStats.BonusPhysicalDamageTaken
	}
	if taken := attackTable.Defender.PseudoStats.BonusDamageTaken; taken != 0 {
		result.Damage += spell.flatDamageTaken(taken, attackTable.Defender, isPeriodic)
	}

	// SpellDamageBonusTaken and MeleeDamageBonusTaken truncate too
	result.Damage = math.Trunc(result.Damage * spell.TargetDamageMultiplier(attackTable, isPeriodic))
}
func (spell *Spell) TargetDamageMultiplier(attackTable *AttackTable, isPeriodic bool) float64 {
	if spell.Flags.Matches(SpellFlagIgnoreTargetModifiers) {
		return 1
	}

	multiplier := attackTable.Defender.PseudoStats.DamageTakenMultiplier *
		attackTable.Defender.PseudoStats.SchoolDamageTakenMultiplier[spell.SchoolIndex] *
		attackTable.DamageTakenMultiplier

	if spell.Flags.Matches(SpellFlagDisease) {
		multiplier *= attackTable.Defender.PseudoStats.DiseaseDamageTakenMultiplier
	}

	if spell.Flags.Matches(SpellFlagHauntSE) {
		multiplier *= attackTable.HauntSEDamageTakenMultiplier
	}

	if spell.SpellSchool.Matches(SpellSchoolNature) {
		multiplier *= attackTable.NatureDamageTakenMultiplier
	} else if spell.takesBleedBonus(isPeriodic) {
		multiplier *= attackTable.Defender.PseudoStats.PeriodicPhysicalDamageTakenMultiplier
	}

	return multiplier
}

func (spell *Spell) CasterHealingMultiplier() float64 {
	if spell.Flags.Matches(SpellFlagIgnoreAttackerModifiers) {
		return 1
	}

	return spell.DamageMultiplier * spell.DamageMultiplierAdditive
}
func (spell *Spell) applyTargetHealingModifiers(damage float64, attackTable *AttackTable) float64 {
	if spell.Flags.Matches(SpellFlagIgnoreTargetModifiers) {
		return damage
	}

	return damage *
		attackTable.Defender.PseudoStats.HealingTakenMultiplier *
		attackTable.HealingDealtMultiplier
}
